package com.sinjeong.crewcalendar.domain.model

/**
 * 2호선 **본선(순환선) 43역**과 두 지선의 역 이름 (v1.6.84).
 *
 * 순수 데이터 + 이름 흡수 함수뿐이다 — 안드로이드를 안 부르므로 JUnit 이 그대로 잠근다.
 *
 * ## 출처
 *
 *  · 역 순서: 서울교통공사 2호선 순환선 **내선(시계 방향)** 순서. 시청에서 출발해
 *    을지로 → 왕십리 → 성수 → 잠실 → 강남 → 사당 → 신림 → 신도림 → 당산 → 홍대입구 →
 *    충정로 를 돌아 다시 시청으로 돌아온다.
 *  · 표기 대조: 2026-09-03 01:00 `realtimePosition/2호선` 실호출로 API 가 주는 `statnNm` 을
 *    직접 확인했다(그 시각 16대). 확인된 표기는 `도림천`·`신정네거리`·`신도림`·`문래`·
 *    `홍대입구`·`을지로입구`·`을지로3가`·`삼성`·`서울대입구`·`건대입구`·`신설동`, 그리고
 *    **꼬리가 붙은 두 개** — `성수종착`·`성수지선`.
 *
 * ## ⚠ API 역명에는 꼬리가 붙는다
 *
 * 위 실호출에서 `statnNm` 이 `"성수종착"`·`"성수지선"` 으로 왔다. `statnTnm`(종착역명)은
 * `"신도림지선"`·`"성수종착"` 처럼 더 자주 붙는다. 그래서 이름 비교는 **반드시 [norm] 을
 * 거친다** — 꼬리(`종착`·`지선`·`역`)와 괄호를 떼고 견준다. [BranchLive] 가 지선에서 쓰는
 * 것과 같은 처방이고, 이걸 안 하면 성수에 있는 열차가 지도에서 통째로 사라진다.
 *
 * 옛 이름이 올 가능성이 있는 곳은 [ALIASES] 한 곳에만 적는다(`신천` = 지금의 `잠실새내`).
 */
object Line2Stations {

    /**
     * 본선 43역 — **내선(시계 방향) 순서**. 마지막 `충정로` 다음이 다시 첫 `시청`이다(순환선).
     *
     * 이 순서가 곧 원 위의 각도이고([MainLineMap]), 인덱스가 [MainTrainMark] 의 좌표다.
     * **순서를 바꾸면 지도의 모든 열차가 어긋난다** — `Line2Test` 가 개수와 순서를 잠근다.
     */
    val MAIN: List<String> = listOf(
        "시청", "을지로입구", "을지로3가", "을지로4가", "동대문역사문화공원",
        "신당", "상왕십리", "왕십리", "한양대", "뚝섬",
        "성수", "건대입구", "구의", "강변", "잠실나루",
        "잠실", "잠실새내", "종합운동장", "삼성", "선릉",
        "역삼", "강남", "교대", "서초", "방배",
        "사당", "낙성대", "서울대입구", "봉천", "신림",
        "신대방", "구로디지털단지", "대림", "신도림", "문래",
        "영등포구청", "당산", "합정", "홍대입구", "신촌",
        "이대", "아현", "충정로",
    )

    /** 성수지선 — 성수에서 갈라져 신설동까지. **표시만** 하고 열차는 그리지 않는다. */
    val SEONGSU_BRANCH: List<String> = listOf("성수", "용답", "신답", "용두", "신설동")

    /** 신정지선 — 신도림에서 갈라져 까치산까지. 이 지선의 실시간은 [BranchLine] 지도가 맡는다. */
    val SINJEONG_BRANCH: List<String> = listOf("신도림", "도림천", "양천구청", "신정네거리", "까치산")

    /** 본선이 아닌 지선 전용역(성수·신도림은 본선이라 뺀다) — 본선 지도에서 걸러 낼 이름들. */
    val BRANCH_ONLY: Set<String> =
        (SEONGSU_BRANCH.drop(1) + SINJEONG_BRANCH.drop(1)).toSet()

    /** 옛 이름 → 지금 이름. 지금까지 필요한 건 하나뿐이라 표를 크게 만들지 않는다. */
    private val ALIASES = mapOf("신천" to "잠실새내")

    /**
     * API 표기 흡수 — 괄호 뒤를 자르고 꼬리(`종착`·`지선`·`역`)를 뗀다.
     *
     * `"성수종착"` → `성수` · `"신도림지선"` → `신도림` · `"까치산역"` → `까치산` ·
     * `"동대문역사문화공원(2호선)"` → `동대문역사문화공원`.
     *
     * ⚠ `역` 을 뗄 때 **`동대문역사문화공원` 이 걸리면 안 된다** — 꼬리에서만 떼고,
     * 떼고 나서 이름이 남지 않거나 본선에 없으면 원래 이름을 그대로 쓴다.
     */
    fun norm(raw: String): String {
        var s = raw.substringBefore('(').trim()
        for (tail in listOf("종착", "지선")) if (s.length > tail.length && s.endsWith(tail)) {
            s = s.dropLast(tail.length)
        }
        if (s.length > 1 && s.endsWith("역") && s !in MAIN) s = s.dropLast(1)
        return ALIASES[s] ?: s
    }

    /** 본선 43역에서의 자리. 지선 전용역·본선 아닌 이름은 **−1**. */
    fun indexOfMain(raw: String): Int = MAIN.indexOf(norm(raw))
}
