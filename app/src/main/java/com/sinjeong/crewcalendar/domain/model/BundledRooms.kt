package com.sinjeong.crewcalendar.domain.model

/**
 * **침실배정표 — 신정 칸만** (v1.6.76).
 *
 * 야간 다이아(본선 33~51 · 지선 지10~14)는 전반 사업을 마치고 사업소 침실에서 자고
 * **기상 시각에 일어나 익일 후반 사업**을 나간다(후반 알람이 익일인 근거는 v1.6.73).
 * 어느 침실에서 몇 시에 일어나는지가 이 표다. 표는 **당일·익일의 평/휴 조합 4종**이고
 * 조합은 [Bundled.comboOf]가 고른다 — v1.6.74가 넣은 이미지 카드와 **같은 값**이다.
 *
 * ## 출처 — **독립된 두 벌을 각각 뽑아 전수 대조했다**
 *
 * | | 원본(읽기 전용) | 뽑은 법 |
 * |---|---|---|
 * | **1차** | `침실배정표 23년10월기준\침실배정표(23.10.04.){평평,평휴,휴평,휴휴}.pdf` | **좌표 기반.** 1쪽짜리 순수 벡터(내장 이미지 0). 세로 괘선 13개로 12칸(좌우 두 벌 × 6컬럼)을 가르고, **가로 괘선이 끊긴 자리로 세로 병합을 판별**해 `기상`의 병합 구간을 복원 |
 * | 2차 | `침실배정표(23.10.04.)_20260826130948.xlsx`의 `2023.10.04. {평평,평휴,휴평,휴휴}` 시트 | `openpyxl` — `merged_cells`로 병합 복원 |
 *
 * **대조 결과: 호실 192칸(48호실 × 4조합)의 `기상`·`신정`이 전부 일치, 불일치 0건.**
 * 다이아 75건 기준으로도 0건. 그림 카드 `assets/routes/room_*.webp` 4장도 **같은 PDF를 렌더**한
 * 것이라 화면에 뜨는 표와 이 값은 같은 출처다(v1.6.76에서 사진 보정본을 PDF 렌더로 교체).
 *
 * 개정일 **2023.10.04.** — 앱의 다른 번들 데이터와 같은 판.
 * 읽은 칸은 **`신정` 열만**. `대림`·`동대문`은 다른 사업소라 안 읽는다 (사용자 확정: *"신정만 할껀데"*).
 *
 * ⚠ 엑셀 파일 안의 `2022.06.07.*` 시트들은 **옛 판이라 값이 다르다**(평평 5호실이 2022판 35 ·
 * 2023판 **34**). 갱신할 때도 `2023.10.04.` 넉 장만 본다.
 *
 * ⚠ **PDF에서 `get_text()`만 쓰면 안 된다** — 표가 평평하게 흘러나와 컬럼이 섞이고, 무엇보다
 * 병합된 `기상` 값이 **병합 구간의 한가운데**에 그려져 있어 글자 좌표만으로는 어느 호실 것인지
 * 못 가른다(2호실 자리에 4:10이 찍히는 식). 괘선을 봐야 한다. 얇은 `re`(두께 2pt 미만)와 `l`만
 * 괘선으로 세고, 표 바깥테·셀 배경 같은 **두꺼운 `re`는 폭이 표 전체라 병합을 가려 버린다.**
 *
 * ## 표에 없는 야간 다이아 = **아무것도 안 보여준다**
 *
 * 잘못된 호실을 보여주는 것이 최악이라([of]가 `null`을 돌려주면 화면이 줄을 통째로 뺀다),
 * 억지로 채우지 않는다. 전수 역검사 결과(본선 33~51 + 지선 지10~14 = 24다이아 × 4조합 = 96칸 중
 * **75칸이 표에 있다**):
 *
 * | 조합 | 표에 없는 다이아 | 왜 (앱이 이미 아는 사실과 맞는다) |
 * |---|---|---|
 * | 전 조합 공통 | **48 · 49 · 50 · 51** | **역 주박** — 홍대입구역·신도림역에서 자고 그 자리에서 출고한다(v1.6.73 "안 켠 것" 표). 표 `기감` 줄의 `홍대 ☎2973` · `신도림 ☎2844`가 그 둘의 연락처다 |
 * | [NightCombo.HH] | **33 · 34 · 35** | **운휴대기** — [MainLegs.NIGHT]에도 휴휴 칸이 없다(v1.6.73 "운휴대기(휴휴 33~35)") |
 * | [NightCombo.PP] **35** · [NightCombo.HP] **43** | 이 둘만 | **군자 침실을 쓴다 — 사용자 확정**(아래) |
 *
 * ### ✅ 평평 35 · 휴평 43은 **정상이다** (v1.6.77, 사용자 확정 — 채우지 말 것)
 *
 * v1.6.76이 *"이 둘만 `신정` 칸이 비어 있는데 근거가 없어 추정하지 않는다"*고 남겨 둔 자리에
 * 사용자가 답을 줬다:
 *
 * > **"평평35, 휴평43는 군자침실이라서 없어도 돼"**
 *
 * 두 근무는 **군자 침실**에서 잔다. 이 표는 `신정` 열만 읽는 표(신정승무사업소 배정)라
 * 그 칸이 비어 있는 것이 **원본이 맞다** — 누락이 아니다. 따라서 [of]가 `null`을 주고
 * 상세시트에 **아무것도 안 뜨는 지금 동작이 정답**이다.
 *
 * ⚠ **다음 세션 주의**: "데이터가 빠졌다"고 오해해 값을 채우거나 *"군자 침실입니다"* 같은
 * 안내 문구를 넣지 말 것. 사용자가 안내도 원하지 않았다(요청은 "없어도 돼"까지다).
 * 군자 침실의 호실·기상시각은 **다른 사업소 표라 이 앱에 자료 자체가 없다.**
 *
 * ## 기상시각 교차검증
 *
 * 75칸 전부 [MainLegs] · [Bundled]의 **후반사업 시작시각보다 57~68분 이르다**(예: 평평 33번 =
 * 7호실 기상 4:50, 후반 5:52 시작 → 62분). 표를 따로 읽어 넣었는데 앱이 이미 가진 시각과
 * 한 칸도 어긋나지 않는다는 뜻이라, 열/행을 밀려 읽었을 가능성이 사실상 없다.
 */
object BundledRooms {

    /** 침실 한 칸. [wake]는 표기 그대로 `H:mm`. */
    data class Room(val no: Int, val wake: String) {
        /** 상세시트 칩 문구 — `7호실 · 기상 4:50` */
        val label: String get() = "${no}호실 · 기상 $wake"
    }

    /**
     * 조합 + 다이아 → 침실. **표에 없으면 `null`** (표시하지 않는다).
