     * [dia]는 [DutyCode.diaRaw] 그대로 넘긴다 — 본선은 `"33"`~`"51"`, 지선 야간은 `"지10"`~`"지14"`.
     * 충당 계열(`"충당 44"`)도 [DutyCode.diaRaw]가 `"44"`만 남기므로 그대로 걸린다.
